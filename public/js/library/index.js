const { nanoid } = require('nanoid')

function generateUniqueId(prefix = 'ID', digit = 30) {
    const timestamp = Date.now() + ''
    return prefix + timestamp + '' + nanoid(digit - (prefix?.length + timestamp?.length))
}

function toNumber(number, digit = 2) {
    return parseFloat(parseFloat(number).toFixed(digit))
}

